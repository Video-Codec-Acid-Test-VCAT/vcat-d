package com.roncatech.vcat.ui;

import android.os.Bundle;
import android.view.LayoutInflater;
import android.view.View;
import android.view.ViewGroup;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.fragment.app.Fragment;

import com.roncatech.vcat.R;

/**
 * A whole view that says "Under Construction", for a tab whose feature is not finished.
 *
 * Shown instead of a half-built UI, so a feature that does not work never looks as if it does.
 * The Export tab uses it: FragmentVectorExport and ExportTestVectors are a partial implementation
 * that is kept in the tree for when the feature is completed, but is not reachable.
 */
public class FragmentUnderConstruction extends Fragment {
    @Nullable
    @Override
    public View onCreateView(@NonNull LayoutInflater inflater,
                             @Nullable ViewGroup container,
                             @Nullable Bundle savedInstanceState) {
        return inflater.inflate(R.layout.fragment_under_construction, container, false);
    }
}
